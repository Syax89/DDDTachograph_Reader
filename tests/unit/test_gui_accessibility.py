@pytest.fixture
def explorer(monkeypatch):
    app = new_explorer(monkeypatch)
    try:
        yield app
    finally:
        gui.DayDetailWindow._open_windows.clear()
        close(app)


def _walk(widget):
    yield widget
    for child in widget.winfo_children():
        yield from _walk(child)


def _nodes(tree, iid="", depth=0):
    """Every node under *iid*, with its 1-based depth (top level is 1)."""
    for child in tree.get_children(iid):
        yield child, depth + 1
        yield from _nodes(tree, child, depth + 1)


def _expand_all(tree):
    """Open every node: a clipped row is only drawn once it is visible."""
    for _ in range(12):
        closed = [iid for iid, _depth in _nodes(tree)
                  if tree.get_children(iid) and not tree.item(iid, "open")]
        if not closed:
            return
        for iid in closed:
            tree.item(iid, open=True)


def _open_mock(app, name):
    """Parse a generated mock through the real render path."""
    path = MOCK_DIR / name
    if not path.is_file():
        pytest.skip(f"{name} is not generated (tests/integration/generate_mock_ddd.py)")
    app._parse_done(TachoParser(str(path)).parse(), str(path))
    app.update()
    return path


def _find_node(app, title):
    """The first node whose own title is *title* (translated or not)."""
    for iid, _depth in _nodes(app.tree):
        if app.tree.item(iid, "text") == title:
            return iid
    return None


def _day_node(app):
    return next((iid for iid, _depth in _nodes(app.tree)
                 if (app._payloads.get(iid) or [None])[0] == "__activity_chart__"), None)


def _focus(app, widget):
    """Give *widget* the keyboard focus, the way a keyboard user would.

    Xvfb runs without a window manager, so no window ever gets the X focus on
    its own and Tk drops generated key events. ``focus_force`` hands it over;
    a real desktop does this when the user clicks or tabs into the window.
    """
    app.focus_force()
    widget.focus_set()
    app.update()


def _row_image(tree, iid):
    """The image name a tree row draws (tkinter returns it as a 1-tuple)."""
    image = tree.item(iid, "image")
    if isinstance(image, (tuple, list)):
        image = image[0] if image else ""
    return str(image)


def _pane(app):
    return next(w for w in _walk(app) if w.winfo_class().lower() == "tpanedwindow")


def _tree_font(app):
    style = ttk.Style(app)
    return tkfont.Font(font=style.lookup("Treeview", "font") or "TkDefaultFont")


def _tree_indent(app):
    return int(ttk.Style(app).lookup("Treeview", "indent") or 20)


# ── R-1: the tree shows every node in full ────────────────────────────────

@pytest.mark.parametrize("name", CLIPPED_TREE_FILES)
@pytest.mark.parametrize("geometry", GEOMETRIES)
def test_no_tree_node_of_a_g2_file_is_clipped(explorer, name, geometry):
    """Every expanded node fits the treeview column it is drawn in.

    The width a row needs is where ttk starts its text — one indent step per
    level (minus the 1 px the item's padding absorbs) plus the row's icon —
    and the width of the text in the font the tree really draws. The column is
    the width Tk clips at, so comparing the two is the same question a
    screenshot asks, without the screenshot.
    """
    explorer.geometry(geometry)
    explorer.update()
    _open_mock(explorer, name)
    _expand_all(explorer.tree)
    explorer.update()

    font = _tree_font(explorer)
    indent = _tree_indent(explorer)
    icon_width = gui._icon_px(16, explorer)
    column = int(explorer.tree.column("#0", "width"))

    clipped = []
    for iid, depth in _nodes(explorer.tree):
        text = explorer.tree.item(iid, "text")
        start = indent * depth - 1
        if explorer.tree.item(iid, "image"):
            start += icon_width
        if start + font.measure(text) > column:
            clipped.append((start + font.measure(text), text))
    assert not clipped, (
        f"tree column is {column} px, clipped rows (needed width, text): "
        f"{sorted(clipped, reverse=True)[:5]}")


@pytest.mark.parametrize("name", CLIPPED_TREE_FILES)
def test_the_tree_pane_still_leaves_the_file_info_table_its_values(explorer, name):
    """Widening the tree must not clip the File Info table at the minimum size.

    The two panes divide one window, so R-1 trades tree width against table
    width. What the table cannot lose is its *values*: every one of the ten
    rows has to fit the column it is drawn in, measured in the font the table
    draws. Tk's cell box is the column width, so this is the same comparison a
    screenshot makes — at the shipped sash the tightest cell (the
    structurally-identified coverage, 275 px) has 7 px to spare.
    """
    explorer.geometry(MINIMUM_SIZE)
    explorer.update()
    _open_mock(explorer, name)

    node = _find_node(explorer, gui._("File Info"))
    assert node is not None, "the File Info section is missing"
    explorer.tree.selection_set(node)
    explorer.update()

    table = explorer.table.tv
    columns = table["columns"]
    widths = {column: int(table.column(column, "width")) for column in columns}
    body_font = tkfont.Font(
        font=ttk.Style(explorer).lookup("Treeview", "font") or "TkDefaultFont")
    needed = {}
    for row in explorer.table._all_rows:
        for index, column in enumerate(columns):
            if index < len(row):
                needed[column] = max(needed.get(column, 0),
                                     body_font.measure(str(row[index])))
    # Assert the exact rows, not a bare count: a row that appears (or vanishes)
    # must be a deliberate change. The File Info section carries these ten facts for
    # every file; "Decoder failures" is only added when the counter is non-zero (a
    # real decoder failure, never a structural observation).
    labels = [row[0] for row in explorer.table._all_rows]
    assert labels == [
        gui._("Filename"), gui._("Size"), gui._("Origin"), gui._("Generation"),
        gui._("Integrity"), gui._("Byte-accounted coverage"), gui._("Unknown bytes"),
        gui._("Structurally identified coverage"), gui._("Parsed at"),
        gui._("App version"),
    ], labels
    for column, width in widths.items():
        assert width >= needed.get(column, 0), (
            f"{column} column is {width} px, its widest cell needs "
            f"{needed.get(column, 0)} px: the tree took too much of the window")


# ── T-3: the day-detail log is drawn in a fixed-pitch font ────────────────

def test_the_mono_font_is_fixed_pitch_on_this_platform(explorer):
    """"Menlo" exists on macOS only; everywhere else it resolved to a sans.

    A proportional font in the log makes every column drift by the width of
    its characters, which is what the log is padded for (``ljust``). Two
    glyphs of very different width must therefore measure the same.
    """
    font = tkfont.Font(font=gui.FONT_MONO)
    assert font.measure("i") == font.measure("W"), (
        f"FONT_MONO resolves to {font.actual('family')!r}, which is not "
        f"fixed-pitch on {sys.platform}")


def test_the_mono_variants_keep_their_size_and_style(explorer):
    """The six mono specs still differ only in size/weight/slant."""
    for spec, size in ((gui.FONT_MONO, 11), (gui.FONT_MONO_BOLD, 11),
                       (gui.FONT_MONO_ITALIC, 11), (gui.FONT_MONO_SMALL, 10),
                       (gui.FONT_MONO_LARGE, 12)):
        assert spec[1] == size
        font = tkfont.Font(font=spec)
        assert font.measure("i") == font.measure("W"), spec
        assert font.actual("size") == size, spec
    assert gui.FONT_MONO_NORMAL[1] == 11


def test_the_day_detail_log_uses_the_mono_font(explorer):
    """The guarantee above is worth nothing if the log does not ask for it."""
    _open_mock(explorer, "mock_g2_card.ddd")
    day = _day_node(explorer)
    assert day is not None, "the mock has no activity day"
    explorer._open_day_detail(day)
    explorer.update()
    windows = [w for w in explorer.winfo_children()
               if isinstance(w, gui.DayDetailWindow)]
    assert windows, "the day-detail window did not open"
    drawn = tkfont.Font(font=windows[0].text.cget("font"))
    assert drawn.actual("family") == tkfont.Font(font=gui.FONT_MONO).actual("family")
    assert drawn.measure("i") == drawn.measure("W")


# ── I-1: the verdict never stops mid-word ─────────────────────────────────

#: The longest verdict ``_integrity_label`` produces, and the data that makes
#: a card file report it.
LONG_VERDICT_INTEGRITY = "Missing ERCA root certificate"
SHORT_VERDICT_INTEGRITY = "Error reading the file"


def _verdict_app(app, integrity, geometry=MINIMUM_SIZE, mock="mock_g2_card.ddd"):
    _open_mock(app, mock)
    app.geometry(geometry)
    app.update()
    app._update_status_badge({"metadata": {"integrity_check": integrity}})
    app.update()
    return app


def test_a_verdict_that_does_not_fit_ends_in_an_ellipsis_and_reveals_in_full(explorer):
    _verdict_app(explorer, LONG_VERDICT_INTEGRITY)
    verdict = gui._("Certificate chain not anchored to a trusted root")
    shown = explorer.lbl_status.cget("text")
    assert shown.endswith("\u2026"), f"clipped without a mark: {shown!r}"
    assert shown != verdict and verdict.startswith(shown[:-1]), (
        f"{shown!r} is not a prefix of the verdict plus an ellipsis: the "
        f"wording of the verdict must not change, only where it is cut")

    explorer.lbl_status.event_generate("<Enter>")
    explorer.update()
    assert explorer._status_tip is not None, "no reveal for the clipped verdict"
    assert explorer._status_tip.cget("text") == verdict
    assert explorer._status_tip.winfo_ismapped()

    explorer.lbl_status.event_generate("<Leave>")
    explorer.update()
    assert not explorer._status_tip.winfo_ismapped()


def test_a_verdict_that_fits_is_shown_whole_and_gets_no_tooltip(explorer):
    # The default window, not the minimum: 900 px has no room left for a
    # verdict that does not cost the generation badge its own width.
    _verdict_app(explorer, SHORT_VERDICT_INTEGRITY, geometry="1280x760")
    verdict = gui._("Verification error")
    assert explorer.lbl_status.cget("text") == verdict
    explorer.lbl_status.event_generate("<Enter>")
    explorer.update()
    assert explorer._status_tip is None or not explorer._status_tip.winfo_ismapped()


def test_the_verdict_is_refitted_when_the_window_grows(explorer):
    """A narrower window may elide; the same window wider must not."""
    _verdict_app(explorer, LONG_VERDICT_INTEGRITY)
    verdict = gui._("Certificate chain not anchored to a trusted root")
    assert explorer.lbl_status.cget("text").endswith("\u2026")
    explorer.geometry("1600x900")
    explorer.update()
    assert explorer.lbl_status.cget("text") == verdict, (
        "the verdict was not re-fitted on resize")


