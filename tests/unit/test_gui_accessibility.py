def _tree_hbar(app):
    return next(w for w in app.tree.master.winfo_children()
                if w.winfo_class() == "TScrollbar"
                and str(w.cget("orient")) == "horizontal")


def _widest_node(app):
    """Pixels the widest node of the tree needs, collapsed nodes included."""
    style = ttk.Style(app)
    font = tkfont.Font(font=style.lookup("Treeview", "font") or "TkDefaultFont")
    indent = int(float(style.lookup("Treeview", "indent") or 20))
    return max(indent * depth - 1 + font.measure(app.tree.item(iid, "text"))
               for iid, depth in _nodes(app.tree))


def test_a_node_wider_than_the_pane_is_reached_by_scrolling_not_cut(explorer):
    """The G2.2 card has node names no fixed pane width fits (33 of 34
    languages overflow it): the column is as wide as the widest label and a
    horizontal scrollbar reaches the end of it."""
    explorer.geometry(MINIMUM_SIZE)
    _open_mock(explorer, "mock_g22_card.ddd")
    explorer.update()
    explorer.update()
    assert int(explorer.tree.column("#0", "width")) >= _widest_node(explorer)
    bar = _tree_hbar(explorer)
    assert bar.winfo_ismapped(), "a node overflows the pane but there is no way to scroll to it"
    explorer.tree.xview_moveto(1.0)
    explorer.update()
    first, last = explorer.tree.xview()
    assert first > 0 and last == 1.0


