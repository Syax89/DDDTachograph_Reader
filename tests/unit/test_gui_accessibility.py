# ── K-3: the integrity banner is reachable from the keyboard ──────────────

def _tab_chain(widget, limit=200):
    """Window names reachable from *widget* with Tab, as Tk computes them."""
    chain, current = [], str(widget)
    for _ in range(limit):
        current = str(widget.tk.call("tk_focusNext", current))
        if not current or current == str(widget) or current in chain:
            break
        chain.append(current)
    return chain


def test_the_integrity_banner_is_a_keyboard_button(explorer, monkeypatch):
    _open_mock(explorer, "mock_g2_card.ddd")       # this file has warnings
    assert explorer.integrity_banner.cget("text"), "the mock is expected to warn"
    explorer.update()
    banner = str(explorer.integrity_banner)
    assert banner in _tab_chain(explorer), "the banner is not in the tab chain"

    calls = []
    monkeypatch.setattr(explorer, "_show_integrity_details",
                        lambda: calls.append("opened"))
    explorer.integrity_banner.event_generate("<Button-1>", x=2, y=2)
    explorer.update()
    assert calls == ["opened"], "the click no longer opens the dialog"

    _focus(explorer, explorer.integrity_banner)
    explorer.integrity_banner.event_generate("<Return>")
    explorer.update()
    assert calls == ["opened", "opened"], "Return does not do what the click does"

    explorer.integrity_banner.event_generate("<space>")
    explorer.update()
    assert calls == ["opened"] * 3


def test_the_integrity_banner_leaves_the_tab_chain_when_it_has_nothing_to_say(explorer):
    """A banner with no warning is not a button: Tab skips it again."""
    _open_mock(explorer, "mock_g2_card.ddd")
    explorer.update()
    assert str(explorer.integrity_banner) in _tab_chain(explorer)
    explorer._reset_file_display()
    explorer.update()
    assert str(explorer.integrity_banner) not in _tab_chain(explorer)


