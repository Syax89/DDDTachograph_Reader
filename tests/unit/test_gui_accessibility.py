"""Keyboard, layout and naming guarantees of the desktop UI.

Every test here is tied to one defect the design review measured, and fails on
the behaviour the product had before it was fixed:

* **R-1 — the tree clipped its own rows.** The sash started at 260 px while the
  widest node of a fully expanded G2 card tree ("EF Signatures (Card Data
  Integrity)", depth 2) needs 289 px at the font the tree actually draws, so
  five of 37 nodes were cut mid-word. The sash is sized from that row and from
  the File Info table's own widest cell at the 900x560 minimum, so neither
  wins at the other's expense.
* **T-3 — the monospace font was macOS only.** ``FONT_MONO`` named "Menlo",
  which Windows and X11 do not have; Tk substitutes the *proportional* default
  font instead of failing, and the day-detail log's columns stopped lining up.
* **I-1 — the integrity verdict was clipped.** The longest one needs 462 px in
  Greek and the toolbar leaves it ~274 px at 900 px wide; Tk cut the words off
  with no ellipsis and no way to read the rest.
* **K-1/K-3/K-5 — mouse-only controls.** The day detail opened only on a double
  click, the integrity banner only on a click, and the table could not be
  copied out at all.
* **P-2/X-1/P-4/S-2 — consistency.** Headings were centred over left-aligned
  cells, the empty state's "Open DDD file" button was an iconless twin of the
  toolbar one, two different nodes shared one icon, and a colour map nothing
  read sat in ``DayDetailWindow``.

The mock ``.ddd`` files these measure are generated by
``tests/integration/generate_mock_ddd.py`` (CI runs it before the suite); a
test that needs one skips when it is absent, the same way the other real-parse
tests do.
"""
import os
import sys
from pathlib import Path

import pytest

pytest.importorskip("tkinter")

import tkinter.font as tkfont  # noqa: E402
from tkinter import ttk  # noqa: E402

